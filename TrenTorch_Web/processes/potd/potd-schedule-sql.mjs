import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildCurriculum } from '../curriculum-build/build.mjs';

// public.potd_schedule is the server's trusted copy of data/potd.ts:
// record_potd_attempt() and record_potd_outcome() reject any question missing
// from it, and take the rating difficulty from it. Run this after adding POTDs
// and commit the output as a new migration:
//
//   npm run potd:schedule-sql > supabase/migrations/<timestamp>_sync_potd_schedule.sql
//
// Rows already in the table are left alone (on conflict do nothing).
const RATING_DIFFICULTY = {
	Beginner: 'easy',
	Intermediate: 'medium',
	Advanced: 'hard',
	Mastery: 'advanced'
};

const ENTRY = /date:\s*'(\d{4}-\d{2}-\d{2})',\s*questionId:\s*'([^']+)'/g;

export function readPotdEntries(
	path = join(fileURLToPath(import.meta.url), '..', '..', '..', 'data', 'potd.ts')
) {
	return [...readFileSync(path, 'utf8').matchAll(ENTRY)].map(([, date, questionId]) => ({
		date,
		questionId
	}));
}

export function questionDifficulties() {
	const map = new Map();
	for (const root of buildCurriculum().bundle.roots)
		for (const section of root.sections)
			for (const track of section.tracks)
				for (const q of track.questions) map.set(q.id, RATING_DIFFICULTY[q.difficulty]);
	return map;
}

export function scheduleRows(entries = readPotdEntries(), difficulties = questionDifficulties()) {
	return entries.map(({ date, questionId }) => {
		const difficulty = difficulties.get(questionId);
		if (!difficulty) throw new Error(`POTD ${date} uses unknown question "${questionId}"`);
		return { questionId, date, difficulty };
	});
}

export function scheduleSql(rows = scheduleRows()) {
	const values = rows.map((r) => `  ('${r.questionId}', '${r.date}', '${r.difficulty}')`);
	return [
		'-- Mirrors data/potd.ts into potd_schedule (generated by `npm run potd:schedule-sql`).',
		'insert into public.potd_schedule (question_id, potd_date, difficulty) values',
		values.join(',\n'),
		'on conflict (question_id) do nothing;',
		''
	].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.stdout.write(scheduleSql());
