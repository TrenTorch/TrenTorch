import numpy as np


def sqrt_all(arr: np.ndarray) -> np.ndarray:
    return np.sqrt(arr)


def exponentiate(arr: np.ndarray) -> np.ndarray:
    return np.exp(arr)


def natural_log(arr: np.ndarray) -> np.ndarray:
    return np.log(arr)


def absolute_values(arr: np.ndarray) -> np.ndarray:
    return np.abs(arr)
