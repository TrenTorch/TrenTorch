def test_join_order_is_forced_with_cross_join(sql):
    assert re.search(r"\bcross\s+join\b", sql.query, re.I), "Use CROSS JOIN: SQLite never reorders the tables of a CROSS JOIN."


def test_regions_is_the_outer_loop(sql):
    plan = sql.plan()
    assert len(plan) >= 2, "Expected two plan steps (one per table). Plan: " + " | ".join(plan)
    assert "regions" in plan[0], "regions should be scanned first (outer loop). Plan: " + " | ".join(plan)


def test_customers_is_looked_up_by_index(sql):
    plan = sql.plan()
    inner = next((step for step in plan if "customers" in step), "")
    assert "SEARCH" in inner and "idx_customers_region" in inner, (
        "customers should be searched through idx_customers_region. Plan: " + " | ".join(plan)
    )
